// Copies Leaflet (JS + CSS) from node_modules into a TypeScript module, so the map works
// without any network access to a CDN: the page that shows the map is built from these strings.
//
//   node tools/map/embed-leaflet.js
//
// Re-run it only if you upgrade the `leaflet` dev dependency. Leaflet is BSD-2-Clause licensed;
// its licence banner is kept at the top of the embedded script.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', '..');
const dist = path.join(root, 'node_modules', 'leaflet', 'dist');
const out = path.join(root, 'src', 'features', 'istanbul', 'leafletBundle.ts');

const version = require(path.join(root, 'node_modules', 'leaflet', 'package.json')).version;
// A literal "</script>" inside an inline <script> would end it early.
const safe = (s) => s.replace(/<\/script/gi, '<\\/script');
const js = safe(fs.readFileSync(path.join(dist, 'leaflet.js'), 'utf8'));
const css = fs.readFileSync(path.join(dist, 'leaflet.css'), 'utf8');

const body =
  `// Generated by tools/map/embed-leaflet.js from leaflet@${version} — do not edit by hand.\n` +
  `// Leaflet is BSD-2-Clause licensed (https://leafletjs.com).\n\n` +
  `export const LEAFLET_VERSION = ${JSON.stringify(version)};\n\n` +
  `export const LEAFLET_JS = ${JSON.stringify(js)};\n\n` +
  `export const LEAFLET_CSS = ${JSON.stringify(css)};\n`;

fs.writeFileSync(out, body);
console.log(`leaflet@${version}: ${Math.round(js.length / 1024)} KB js + ${Math.round(css.length / 1024)} KB css -> ${path.relative(root, out)}`);
